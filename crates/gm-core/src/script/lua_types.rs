//! The files a Lua language server reads to complete a workflow in the person's own editor
//! (D233): `.api/gitmaster.lua`, a definition file in the annotation format of the Lua language
//! server (`LuaLS`), and the `.luarc.json` that makes a workflows folder a workspace of it. Both are
//! generated from the `ctx` surface and the metadata fields, as the rest of `.api/` is, so the
//! editor cannot drift from the sandbox.

