/// The definition file: the metadata, the results, then one class per namespace of `ctx`.
pub(super) fn lua_types(surface: &CtxSurface) -> String {
    let mut out = String::from(HEADER);
    meta_classes(&mut out);
    out.push_str(RESULTS);
    let outcomes: Vec<String> = WAIT_OUTCOMES.iter().map(|o| format!("\"{o}\"")).collect();
    let _ = writeln!(
        out,
        "---@class gitmaster.WaitResult\n---@field outcome {}\n",
        outcomes.join("|")
    );
    for f in surface.functions() {
        if let Some(class) = args_class(f) {
            out.push_str(&class);
        }
    }
    let groups = grouped(surface);
    for (space, functions) in &groups {
        if space.is_empty() {
            continue;
        }
        let class = format!("Ctx{}", pascal(space));
        let _ = writeln!(out, "---@class gitmaster.{class}\nlocal {class} = {{}}\n");
        for f in functions {
            function(&mut out, &class, method(f.path), f);
        }
    }
    out.push_str("---The first argument of `M.execute`: the only way a workflow acts.\n");
    out.push_str("---@class gitmaster.Ctx\n");
    for space in groups.keys().filter(|space| !space.is_empty()) {
        let _ = writeln!(out, "---@field {space} gitmaster.Ctx{}", pascal(space));
    }
    out.push_str("local Ctx = {}\n\n");
    for f in surface
        .functions()
        .iter()
        .filter(|f| namespace(f.path).is_empty())
    {
        function(&mut out, "Ctx", f.path, f);
    }
    for helper in HELPERS {
        helper_function(&mut out, helper);
    }
    out
}

/// The language server's settings for a workflows folder: Lua 5.1 with the Luau operators the
/// sandbox accepts, without the libraries the sandbox removes, and `library` as a library, so
/// its definitions complete and are not checked as workflows.
pub(super) fn luarc(library: &str) -> String {
    let value = serde_json::json!({
        "runtime.version": "Lua 5.1",
        "runtime.nonstandardSymbol": ["continue", "+=", "-=", "*=", "/=", "%=", "^=", "//="],
        "runtime.builtin": {
            "io": "disable",
            "os": "disable",
            "debug": "disable",
            "package": "disable",
            "ffi": "disable",
            "jit": "disable",
            "bit32": "enable",
            "utf8": "enable",
        },
        "workspace.library": [library],
        "workspace.checkThirdParty": false,
    });
    let mut text = serde_json::to_string_pretty(&value).unwrap_or_default();
    text.push('\n');
    text
}

/// `gitmaster.Trigger`, `gitmaster.InputSpec` and `gitmaster.Meta`, from the fields `meta` reads.
fn meta_classes(out: &mut String) {
    out.push_str("---@alias gitmaster.TriggerName\n");
    for on in catalog::triggers() {
        let _ = writeln!(out, "---| \"{on}\"");
    }
    out.push_str("\n---@class gitmaster.Trigger\n");
    for field in meta::TRIGGER_FIELDS {
        let (optional, ty) = match *field {
            "on" => ("", "gitmaster.TriggerName"),
            _ => ("?", "string"),
        };
        let _ = writeln!(
            out,
            "---@field {field}{optional} {ty} {}",
            trigger_help(field)
        );
    }
    out.push_str("\n---@class gitmaster.InputSpec\n");
    let types: Vec<String> = meta::INPUT_TYPES
        .iter()
        .map(|ty| format!("\"{ty}\""))
        .collect();
    for field in meta::INPUT_FIELDS {
        let ty = if *field == "type" {
            types.join("|")
        } else {
            "string".to_owned()
        };
        let _ = writeln!(out, "---@field {field}? {ty} {}", input_field_help(field));
    }
    out.push_str("\n---What `M.meta` holds. GitMaster reads it without running `execute`.\n");
    out.push_str("---@class gitmaster.Meta\n");
    for field in meta::FIELDS {
        let (optional, ty) = meta_field(field);
        let _ = writeln!(out, "---@field {field}{optional} {ty} {}", meta_help(field));
    }
    out.push('\n');
}

/// Whether a field of `M.meta` may be left out (`?`), and its type.
fn meta_field(field: &str) -> (&'static str, String) {
    match field {
        "name" => ("", "string".to_owned()),
        "trigger" => ("", "gitmaster.Trigger".to_owned()),
        "concurrency" => (
            "?",
            [Concurrency::Queue, Concurrency::Replace, Concurrency::Skip]
                .iter()
                .map(|c| format!("\"{}\"", c.as_str()))
                .collect::<Vec<_>>()
                .join("|"),
        ),
        "inputs" => ("?", "table<string, gitmaster.InputSpec>".to_owned()),
        "review" => ("?", "boolean".to_owned()),
        _ => ("?", "string".to_owned()),
    }
}

/// The class of a call's table: every field of a table call, or the fields after the positional
/// ones (`gitmaster.ExecOpts`). `None` when the call takes no table.
fn args_class(f: &CtxFn) -> Option<String> {
    let fields = table_fields(f);
    if fields.is_empty() {
        return None;
    }
    let mut out = format!("---@class {}\n", args_name(f));
    for field in fields {
        let optional = if field.required { "" } else { "?" };
        let _ = writeln!(
            out,
            "---@field {}{optional} {} {}",
            field.name,
            lua_type(field.kind),
            field.help
        );
    }
    out.push('\n');
    Some(out)
}

/// The fields a call takes in its table.
fn table_fields(f: &CtxFn) -> Vec<&FieldSpec> {
    match &f.shape {
        ArgShape::Table => f.fields.iter().collect(),
        ArgShape::Positional(names) => f
            .fields
            .iter()
            .filter(|field| !names.contains(&field.name))
            .collect(),
    }
}

fn args_name(f: &CtxFn) -> String {
    let suffix = match f.shape {
        ArgShape::Table => "Args",
        ArgShape::Positional(_) => "Opts",
    };
    format!("gitmaster.{}{suffix}", pascal(f.path))
}

/// One function of `ctx`: what the reference says about it, its parameters and its result.
fn function(out: &mut String, class: &str, name: &str, f: &CtxFn) {
    doc(out, &function_summary(f));
    let mut params: Vec<&str> = Vec::new();
    if let ArgShape::Positional(names) = &f.shape {
        for field in names
            .iter()
            .filter_map(|name| f.fields.iter().find(|field| field.name == *name))
        {
            let optional = if field.required { "" } else { "?" };
            let _ = writeln!(
                out,
                "---@param {}{optional} {} {}",
                field.name,
                lua_type(field.kind),
                field.help
            );
            params.push(field.name);
        }
    }
    let table = table_fields(f);
    if !table.is_empty() {
        let (param, optional) = match f.shape {
            ArgShape::Table if table.iter().any(|field| field.required) => ("args", ""),
            ArgShape::Table => ("args", "?"),
            ArgShape::Positional(_) => ("opts", "?"),
        };
        let _ = writeln!(out, "---@param {param}{optional} {}", args_name(f));
        params.push(param);
    }
    if let Some(result) = result_type(f.path) {
        let _ = writeln!(out, "---@return {result}");
    }
    let _ = writeln!(out, "function {class}.{name}({}) end\n", params.join(", "));
}

fn helper_function(out: &mut String, name: &str) {
    if let Some((_, text)) = helper_summary(name) {
        doc(out, &text);
    }
    let (annotations, params) = match name {
        "now" | "random" => ("---@return number\n", ""),
        "block" | "fail" => ("---@param reason string\n", "reason"),
        "try" => (
            "---@param fn fun(): any\n---@return gitmaster.TryResult\n",
            "fn",
        ),
        _ => ("", ""),
    };
    out.push_str(annotations);
    let _ = writeln!(out, "function Ctx.{name}({params}) end\n");
}

/// A description: each line of `text` as a `---` comment line.
fn doc(out: &mut String, text: &str) {
    for line in text.lines() {
        if line.is_empty() {
            out.push_str("---\n");
        } else {
            let _ = writeln!(out, "---{line}");
        }
    }
}

fn lua_type(kind: FieldKind) -> String {
    match kind {
        FieldKind::Text | FieldKind::Duration => "string".to_owned(),
        FieldKind::Choice(values) => values
            .iter()
            .map(|value| format!("\"{value}\""))
            .collect::<Vec<_>>()
            .join("|"),
        FieldKind::TextList => "string[]".to_owned(),
        FieldKind::Bool => "boolean".to_owned(),
        FieldKind::Any => "any".to_owned(),
    }
}

/// The type of a call's result (D105, D106); `None` for a call with no result fields. It names
/// the same calls as the Luau type file (`api_docs::result_type`), which a test checks.
fn result_type(path: &str) -> Option<&'static str> {
    Some(match path {
        "exec" => "gitmaster.ExecResult",
        "approve" => "boolean",
        "wait" => "gitmaster.WaitResult",
        "commit.create" => "gitmaster.CommitResult",
        "restack.plan" | "reparent.plan" => "gitmaster.PlanResult",
        "stack.tree" => "gitmaster.StackTree",
        "stack.stale" => "gitmaster.StaleBranches",
        "scorecards" => "gitmaster.Scorecard[]",
        "change" => "gitmaster.Change",
        _ => return None,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::script::api_docs;

    /// The words of Lua and Luau that cannot follow a dot in a definition.
    const KEYWORDS: &[&str] = &[
        "and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in",
        "local", "nil", "not", "or", "repeat", "return", "then", "true", "until", "while",
    ];

    fn types() -> String {
        lua_types(&CtxSurface::from_catalog())
    }

    #[test]
    fn the_file_is_a_definition_file_and_declares_every_function_of_ctx() {
        let surface = CtxSurface::from_catalog();
        let types = types();
        assert!(types.starts_with("---@meta\n"));
        for f in surface.functions() {
            let (class, name) = match f.path.split_once('.') {
                Some((space, name)) => (format!("Ctx{}", pascal(space)), name),
                None => ("Ctx".to_owned(), f.path),
            };
            assert!(
                types.contains(&format!("\nfunction {class}.{name}(")),
                "{}",
                f.path
            );
            for field in f.fields {
                assert!(
                    types.contains(&format!("{} ", field.name))
                        || types.contains(&format!("{}? ", field.name)),
                    "{} {}",
                    f.path,
                    field.name
                );
            }
        }
        for helper in HELPERS {
            assert!(
                types.contains(&format!("\nfunction Ctx.{helper}(")),
                "{helper}"
            );
        }
    }

    #[test]
    fn every_class_a_line_names_is_declared() {
        let types = types();
        let declared: Vec<&str> = types
            .lines()
            .filter_map(|line| {
                line.strip_prefix("---@class ")
                    .or_else(|| line.strip_prefix("---@alias "))
            })
            .collect();
        let mut seen = 0;
        for word in types.split(|c: char| !(c.is_alphanumeric() || c == '.' || c == '_')) {
            if word.starts_with("gitmaster.") && word.len() > "gitmaster.".len() {
                assert!(declared.contains(&word), "{word} is used and not declared");
                seen += 1;
            }
        }
        assert!(seen > declared.len(), "the classes are used");
    }

    #[test]
    fn no_name_after_a_dot_is_a_keyword() {
        for f in CtxSurface::from_catalog().functions() {
            for segment in f.path.split('.') {
                assert!(!KEYWORDS.contains(&segment), "{}", f.path);
            }
        }
        for helper in HELPERS {
            assert!(!KEYWORDS.contains(helper), "{helper}");
        }
    }

    #[test]
    fn a_table_call_takes_its_class_and_a_positional_call_its_names() {
        let types = types();
        assert!(types.contains("---@class gitmaster.BranchCreateArgs\n---@field name string "));
        assert!(types.contains(
            "---@param args gitmaster.BranchCreateArgs\nfunction CtxBranch.create(args) end"
        ));
        assert!(types.contains("---@param argv string[] "));
        assert!(types.contains(
            "---@param opts? gitmaster.ExecOpts\n---@return gitmaster.ExecResult\nfunction Ctx.exec(argv, opts) end"
        ));
        assert!(types.contains("function CtxStage.all() end"));
    }

    #[test]
    fn the_results_name_the_same_calls_as_the_luau_types() {
        for f in CtxSurface::from_catalog().functions() {
            assert_eq!(
                result_type(f.path).is_none(),
                api_docs::result_type(f.path) == "()",
                "{}",
                f.path
            );
        }
    }

    #[test]
    fn the_metadata_lists_every_field_trigger_and_wait_outcome() {
        let types = types();
        for field in meta::FIELDS {
            assert!(types.contains(&format!("---@field {field}")), "{field}");
        }
        for on in catalog::triggers() {
            assert!(types.contains(&format!("---| \"{on}\"\n")), "{on}");
        }
        for outcome in WAIT_OUTCOMES {
            assert!(types.contains(&format!("\"{outcome}\"")), "{outcome}");
        }
        assert!(types.contains("---@field name string "));
        assert!(types.contains("---@field trigger gitmaster.Trigger "));
        assert!(types.contains("---@field concurrency? \"queue\"|\"replace\"|\"skip\" "));
    }

    #[test]
    fn every_line_is_an_annotation_a_comment_a_stub_or_blank() {
        for line in types().lines() {
            let ok = line.is_empty()
                || line.starts_with("--")
                || (line.starts_with("local Ctx") && line.ends_with(" = {}"))
                || (line.starts_with("function Ctx") && line.ends_with(") end"));
            assert!(ok, "{line}");
        }
    }

    #[test]
    fn the_settings_are_json_that_names_the_library_and_removes_the_sandboxed_libraries() {
        let text = luarc(".api");
        let value: serde_json::Value = serde_json::from_str(&text).expect("JSON");
        assert_eq!(value["workspace.library"], serde_json::json!([".api"]));
        assert_eq!(value["runtime.version"], "Lua 5.1");
        for library in ["io", "os", "debug", "package"] {
            assert_eq!(value["runtime.builtin"][library], "disable", "{library}");
        }
        assert!(text.ends_with("}\n"));
    }
}
